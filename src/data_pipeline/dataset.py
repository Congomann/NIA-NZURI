import os
import glob
from typing import Optional, List, Tuple
import torch
from torch.utils.data import Dataset, DataLoader
import torchaudio

class SwahiliSpeechDataset(Dataset):
    """
    PyTorch Dataset for loading uniform preprocessed Swahili audio chunks.
    Assumes 16kHz mono WAV chunks generated by preprocess.py.
    """
    def __init__(
        self,
        data_dir: str = "./data/processed_training_chunks",
        target_sample_rate: int = 16000,
        target_channels: int = 1,
        max_duration_sec: Optional[float] = 5.0
    ):
        self.data_dir = data_dir
        self.target_sample_rate = target_sample_rate
        self.target_channels = target_channels
        self.max_duration_sec = max_duration_sec
        self.max_samples = int(target_sample_rate * max_duration_sec) if max_duration_sec else None

        # Gather all valid audio files
        self.file_list: List[str] = sorted(
            glob.glob(os.path.join(self.data_dir, "*.wav")) +
            glob.glob(os.path.join(self.data_dir, "*.flac"))
        )

    def __len__(self) -> int:
        return len(self.file_list)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, int, str]:
        file_path = self.file_list[idx]
        waveform, sample_rate = torchaudio.load(file_path)

        # 1. Resample if necessary
        if sample_rate != self.target_sample_rate:
            resampler = torchaudio.transforms.Resample(
                orig_freq=sample_rate,
                new_freq=self.target_sample_rate
            )
            waveform = resampler(waveform)

        # 2. Convert to mono if multi-channel
        if waveform.shape[0] > self.target_channels:
            waveform = torch.mean(waveform, dim=0, keepdim=True)

        # 3. Uniform sample length padding or truncation
        if self.max_samples is not None:
            num_samples = waveform.shape[-1]
            if num_samples < self.max_samples:
                pad_amount = self.max_samples - num_samples
                waveform = torch.nn.functional.pad(waveform, (0, pad_amount))
            elif num_samples > self.max_samples:
                waveform = waveform[:, :self.max_samples]

        filename = os.path.basename(file_path)
        return waveform, self.target_sample_rate, filename


def speech_collate_fn(batch: List[Tuple[torch.Tensor, int, str]]) -> Tuple[torch.Tensor, List[str]]:
    """
    Collates a list of (waveform, sample_rate, filename) tuples into a batch tensor.
    Returns:
        batched_waveforms: Tensor of shape (B, C, T)
        filenames: List of source file names
    """
    waveforms, _, filenames = zip(*batch)
    batched_waveforms = torch.stack(waveforms, dim=0)
    return batched_waveforms, list(filenames)


def get_speech_dataloader(
    data_dir: str = "./data/processed_training_chunks",
    batch_size: int = 16,
    shuffle: bool = True,
    num_workers: int = 0,
    pin_memory: bool = True
) -> DataLoader:
    """
    Creates and returns a PyTorch DataLoader streaming wrapper around SwahiliSpeechDataset.
    """
    dataset = SwahiliSpeechDataset(data_dir=data_dir)
    dataloader = DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        pin_memory=pin_memory if torch.cuda.is_available() else False,
        collate_fn=speech_collate_fn
    )
    return dataloader


def swahili_waveform_collate_fn(batch: List[Tuple[torch.Tensor, int, str]]) -> torch.Tensor:
    """
    Collates batch items and returns raw waveforms [Batch, TimeSteps] (e.g. [Batch, 80000]).
    """
    waveforms, _, _ = zip(*batch)
    return torch.stack([w.squeeze(0) if w.dim() > 1 else w for w in waveforms], dim=0)


def get_swahili_dataloader(
    data_dir: str = "./data/processed_training_chunks",
    batch_size: int = 8,
    shuffle: bool = True,
    num_workers: int = 0,
    pin_memory: bool = False
) -> DataLoader:
    """
    Convenience DataLoader returning pure waveform tensors [Batch, 80000] for direct training.
    """
    dataset = SwahiliSpeechDataset(data_dir=data_dir)
    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        pin_memory=pin_memory and torch.cuda.is_available(),
        collate_fn=swahili_waveform_collate_fn
    )


if __name__ == "__main__":
    PROCESSED_DATA_DIR = "./data/processed_training_chunks"
    
    if not os.path.exists(PROCESSED_DATA_DIR) or len(glob.glob(os.path.join(PROCESSED_DATA_DIR, "*.wav"))) == 0:
        print(f"No audio files found in {PROCESSED_DATA_DIR}. Testing with a synthesized 16kHz test sample...")
        os.makedirs(PROCESSED_DATA_DIR, exist_ok=True)
        test_file = os.path.join(PROCESSED_DATA_DIR, "tz_swahili_sample_test.wav")
        # Synthesize 5 seconds of 16kHz sine wave audio
        sample_rate = 16000
        t = torch.linspace(0, 5, sample_rate * 5)
        waveform = (torch.sin(2 * torch.pi * 440 * t) * 0.5).unsqueeze(0)
        torchaudio.save(test_file, waveform, sample_rate)
        created_temp = True
    else:
        created_temp = False

    try:
        loader = get_speech_dataloader(data_dir=PROCESSED_DATA_DIR, batch_size=2, shuffle=False)
        print(f"Dataset total samples: {len(loader.dataset)}")
        for batch_waveforms, filenames in loader:
            print(f"Loaded batch shape: {batch_waveforms.shape} | Files: {filenames}")
            break
        print("DataLoader verification successful!")
    finally:
        if created_temp and os.path.exists(test_file):
            os.remove(test_file)
